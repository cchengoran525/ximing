// ---- 最终 Boss：议长（32×32） ----
// 居中辅助：按内容自动补透明边（32 宽）
function sym32(...rows) {
  return rows.map(r => {
    if (!r) return '.'.repeat(32);
    const pad = 32 - r.length;
    const left = pad >> 1;
    return '.'.repeat(left) + r + '.'.repeat(pad - left);
  });
}

